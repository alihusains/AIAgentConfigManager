/**
 * Group providers by category for UI display
 */
export function groupProvidersByCategory(): Record<string, KnownProvider[]> {
  const groups: Record<string, KnownProvider[]> = {};

  KNOWN_PROVIDERS.forEach((provider) => {
    if (!groups[provider.category]) {
      groups[provider.category] = [];
    }
    groups[provider.category].push(provider);
  });

  return groups;
}

/**
 * Get all providers sorted by popularity
 */
export function getPopularProviders(): KnownProvider[] {
  const categoryOrder: Record<string, number> = {
    popular: 0,
    specialized: 1,
    enterprise: 2,
    opensource: 3,
    local: 4,
    emerging: 5,
  };

  return [...KNOWN_PROVIDERS].sort(
    (a, b) => (categoryOrder[a.category] ?? 999) - (categoryOrder[b.category] ?? 999)
  );
}

/**
 * Search providers by name or description
 */
export function searchProviders(query: string): KnownProvider[] {
  const q = query.toLowerCase();
  return KNOWN_PROVIDERS.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.description.toLowerCase().includes(q) ||
      p.id.toLowerCase().includes(q)
  );
}

/**
 * Get provider by ID
 */
export function getProviderById(id: string): KnownProvider | undefined {
  return KNOWN_PROVIDERS.find((p) => p.id === id);
}
